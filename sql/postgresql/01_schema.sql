-- =====================================================================
-- ВетКлиник. PostgreSQL. Шаг 1: схема базы данных (8 таблиц).
-- Запуск от владельца БД:
--   psql -h localhost -U vet_app -d vet_clinic -f sql/postgresql/01_schema.sql
-- Скрипт пересоздаёт все объекты, данные при этом удаляются.
-- =====================================================================

SET client_encoding = 'UTF8';

DROP VIEW  IF EXISTS v_appointment_total;
DROP TABLE IF EXISTS appointment_service, appointment, service, vet,
                     specialization, pet, owner, species CASCADE;
DROP FUNCTION IF EXISTS fn_appointment_rules() CASCADE;
DROP FUNCTION IF EXISTS fn_appointment_service_rules() CASCADE;

-- ---------------------------------------------------------------------
-- 1. Вид животного (справочник)
-- ---------------------------------------------------------------------
CREATE TABLE species (
    species_id   INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    species_name VARCHAR(40) NOT NULL,
    CONSTRAINT pk_species       PRIMARY KEY (species_id),
    CONSTRAINT uq_species_name  UNIQUE (species_name),
    CONSTRAINT ck_species_name  CHECK (length(trim(species_name)) > 0)
);

-- ---------------------------------------------------------------------
-- 2. Владелец питомца
-- ---------------------------------------------------------------------
CREATE TABLE owner (
    owner_id      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    last_name     VARCHAR(50)  NOT NULL,
    first_name    VARCHAR(50)  NOT NULL,
    middle_name   VARCHAR(50),
    phone         VARCHAR(12)  NOT NULL,
    email         VARCHAR(100),
    address       VARCHAR(200),
    registered_on DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_owner        PRIMARY KEY (owner_id),
    CONSTRAINT uq_owner_phone  UNIQUE (phone),
    -- в PostgreSQL UNIQUE допускает много NULL, поэтому отдельный индекс не нужен
    CONSTRAINT uq_owner_email  UNIQUE (email),
    CONSTRAINT ck_owner_names  CHECK (length(trim(last_name)) > 0 AND length(trim(first_name)) > 0),
    CONSTRAINT ck_owner_phone  CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT ck_owner_email  CHECK (email LIKE '_%@_%._%')
);

-- ---------------------------------------------------------------------
-- 3. Питомец
-- ---------------------------------------------------------------------
CREATE TABLE pet (
    pet_id      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    owner_id    INTEGER      NOT NULL,
    species_id  INTEGER      NOT NULL,
    pet_name    VARCHAR(40)  NOT NULL,
    breed       VARCHAR(60),
    sex         CHAR(1)      NOT NULL,
    birth_date  DATE,
    weight_kg   NUMERIC(6,2),
    chip_number CHAR(15),
    CONSTRAINT pk_pet          PRIMARY KEY (pet_id),
    CONSTRAINT fk_pet_owner    FOREIGN KEY (owner_id)   REFERENCES owner (owner_id),
    CONSTRAINT fk_pet_species  FOREIGN KEY (species_id) REFERENCES species (species_id),
    CONSTRAINT uq_pet_chip     UNIQUE (chip_number),
    CONSTRAINT ck_pet_name     CHECK (length(trim(pet_name)) > 0),
    CONSTRAINT ck_pet_sex      CHECK (sex IN ('M', 'F')),
    -- CURRENT_DATE в CHECK: PostgreSQL это допускает, проверка идёт при каждом INSERT/UPDATE
    CONSTRAINT ck_pet_birth    CHECK (birth_date BETWEEN DATE '1980-01-01' AND CURRENT_DATE),
    CONSTRAINT ck_pet_weight   CHECK (weight_kg > 0 AND weight_kg < 1000),
    CONSTRAINT ck_pet_chip     CHECK (chip_number ~ '^[0-9]{15}$')
);
CREATE INDEX ix_pet_owner   ON pet (owner_id);
CREATE INDEX ix_pet_species ON pet (species_id);

-- ---------------------------------------------------------------------
-- 4. Специализация врача (справочник)
-- ---------------------------------------------------------------------
CREATE TABLE specialization (
    specialization_id   INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    specialization_name VARCHAR(60) NOT NULL,
    CONSTRAINT pk_specialization      PRIMARY KEY (specialization_id),
    CONSTRAINT uq_specialization_name UNIQUE (specialization_name),
    CONSTRAINT ck_specialization_name CHECK (length(trim(specialization_name)) > 0)
);

-- ---------------------------------------------------------------------
-- 5. Врач
-- ---------------------------------------------------------------------
CREATE TABLE vet (
    vet_id            INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    specialization_id INTEGER     NOT NULL,
    last_name         VARCHAR(50) NOT NULL,
    first_name        VARCHAR(50) NOT NULL,
    middle_name       VARCHAR(50),
    phone             VARCHAR(12) NOT NULL,
    hire_date         DATE        NOT NULL,
    is_active         BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_vet                PRIMARY KEY (vet_id),
    CONSTRAINT fk_vet_specialization FOREIGN KEY (specialization_id)
                                     REFERENCES specialization (specialization_id),
    CONSTRAINT uq_vet_phone          UNIQUE (phone),
    CONSTRAINT ck_vet_names          CHECK (length(trim(last_name)) > 0 AND length(trim(first_name)) > 0),
    CONSTRAINT ck_vet_phone          CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT ck_vet_hire_date      CHECK (hire_date BETWEEN DATE '1980-01-01' AND CURRENT_DATE)
);
CREATE INDEX ix_vet_specialization ON vet (specialization_id);

-- ---------------------------------------------------------------------
-- 6. Услуга клиники (текущий прайс)
-- ---------------------------------------------------------------------
CREATE TABLE service (
    service_id   INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    service_name VARCHAR(100)  NOT NULL,
    price        NUMERIC(10,2) NOT NULL,
    is_active    BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_service       PRIMARY KEY (service_id),
    CONSTRAINT uq_service_name  UNIQUE (service_name),
    CONSTRAINT ck_service_name  CHECK (length(trim(service_name)) > 0),
    CONSTRAINT ck_service_price CHECK (price >= 0)
);

-- ---------------------------------------------------------------------
-- 7. Приём (запись питомца к врачу)
-- ---------------------------------------------------------------------
CREATE TABLE appointment (
    appointment_id INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    pet_id         INTEGER      NOT NULL,
    vet_id         INTEGER      NOT NULL,
    start_time     TIMESTAMP(0) NOT NULL,
    status         VARCHAR(10)  NOT NULL DEFAULT 'SCHEDULED',
    complaint      VARCHAR(500),
    diagnosis      VARCHAR(500),
    CONSTRAINT pk_appointment        PRIMARY KEY (appointment_id),
    CONSTRAINT fk_appointment_pet    FOREIGN KEY (pet_id) REFERENCES pet (pet_id),
    CONSTRAINT fk_appointment_vet    FOREIGN KEY (vet_id) REFERENCES vet (vet_id),
    CONSTRAINT ck_appointment_status CHECK (status IN ('SCHEDULED', 'DONE', 'CANCELLED')),
    -- слоты по 30 минут с 08:00 до 19:30
    CONSTRAINT ck_appointment_slot   CHECK (EXTRACT(HOUR FROM start_time) BETWEEN 8 AND 19
                                       AND EXTRACT(MINUTE FROM start_time) IN (0, 30)
                                       AND EXTRACT(SECOND FROM start_time) = 0),
    -- у проведённого приёма обязательно есть диагноз
    CONSTRAINT ck_appointment_done   CHECK (status <> 'DONE'
                                       OR (diagnosis IS NOT NULL AND length(trim(diagnosis)) > 0))
);
-- BR-12, BR-13: неотменённые приёмы врача и питомца не пересекаются по времени
CREATE UNIQUE INDEX ux_appointment_vet_slot ON appointment (vet_id, start_time)
    WHERE status IN ('SCHEDULED', 'DONE');
CREATE UNIQUE INDEX ux_appointment_pet_slot ON appointment (pet_id, start_time)
    WHERE status IN ('SCHEDULED', 'DONE');
CREATE INDEX ix_appointment_start ON appointment (start_time);

-- ---------------------------------------------------------------------
-- 8. Услуга, оказанная на приёме (разрешение связи M:N appointment—service)
-- ---------------------------------------------------------------------
CREATE TABLE appointment_service (
    appointment_id INTEGER       NOT NULL,
    service_id     INTEGER       NOT NULL,
    quantity       SMALLINT      NOT NULL DEFAULT 1,
    price          NUMERIC(10,2) NOT NULL,   -- цена на момент оказания
    CONSTRAINT pk_appointment_service PRIMARY KEY (appointment_id, service_id),
    CONSTRAINT fk_aps_appointment     FOREIGN KEY (appointment_id)
                                      REFERENCES appointment (appointment_id) ON DELETE CASCADE,
    CONSTRAINT fk_aps_service         FOREIGN KEY (service_id) REFERENCES service (service_id),
    CONSTRAINT ck_aps_quantity        CHECK (quantity BETWEEN 1 AND 100),
    CONSTRAINT ck_aps_price           CHECK (price >= 0)
);
CREATE INDEX ix_aps_service ON appointment_service (service_id);

-- ---------------------------------------------------------------------
-- Триггер приёма: BR-15 (неактивный врач), BR-16 (смена конечного статуса),
-- BR-17 (нельзя отменить приём, по которому уже оказаны услуги)
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_appointment_rules() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.status IN ('DONE', 'CANCELLED') AND NEW.status <> OLD.status THEN
        RAISE EXCEPTION 'Приём уже проведён или отменён: изменить его статус нельзя';
    END IF;

    -- проверяем врача, только если запись новая или её перенесли
    IF NEW.status = 'SCHEDULED'
       AND (TG_OP = 'INSERT' OR NEW.vet_id <> OLD.vet_id OR NEW.start_time <> OLD.start_time) THEN
        IF NOT EXISTS (SELECT 1 FROM vet WHERE vet_id = NEW.vet_id AND is_active) THEN
            RAISE EXCEPTION 'Врач не работает в клинике: запись к нему невозможна';
        END IF;
    END IF;

    IF NEW.status = 'CANCELLED'
       AND EXISTS (SELECT 1 FROM appointment_service WHERE appointment_id = NEW.appointment_id) THEN
        RAISE EXCEPTION 'По приёму уже оказаны услуги: отменить его нельзя';
    END IF;

    RETURN NEW;
END $$;

CREATE TRIGGER trg_appointment_rules
    BEFORE INSERT OR UPDATE ON appointment
    FOR EACH ROW EXECUTE FUNCTION fn_appointment_rules();

-- ---------------------------------------------------------------------
-- Триггер услуг приёма: BR-17 (отменённый приём, неактивная услуга)
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_appointment_service_rules() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_status appointment.status%TYPE;
    v_active service.is_active%TYPE;
BEGIN
    SELECT status INTO v_status FROM appointment WHERE appointment_id = NEW.appointment_id;
    IF v_status = 'CANCELLED' THEN
        RAISE EXCEPTION 'Приём отменён: добавлять в него услуги нельзя';
    END IF;

    IF TG_OP = 'INSERT' OR NEW.service_id <> OLD.service_id THEN
        SELECT is_active INTO v_active FROM service WHERE service_id = NEW.service_id;
        IF v_active = FALSE THEN
            RAISE EXCEPTION 'Услуга больше не оказывается: добавить её нельзя';
        END IF;
    END IF;

    RETURN NEW;   -- если приёма/услуги нет, сработает внешний ключ
END $$;

CREATE TRIGGER trg_appointment_service_rules
    BEFORE INSERT OR UPDATE ON appointment_service
    FOR EACH ROW EXECUTE FUNCTION fn_appointment_service_rules();

-- ---------------------------------------------------------------------
-- Представление: сумма счёта по каждому приёму
-- ---------------------------------------------------------------------
CREATE VIEW v_appointment_total AS
SELECT a.appointment_id,
       a.start_time,
       a.status,
       a.pet_id,
       a.vet_id,
       COUNT(s.service_id)                     AS service_count,
       COALESCE(SUM(s.price * s.quantity), 0)  AS total_amount
FROM appointment a
LEFT JOIN appointment_service s ON s.appointment_id = a.appointment_id
GROUP BY a.appointment_id, a.start_time, a.status, a.pet_id, a.vet_id;
